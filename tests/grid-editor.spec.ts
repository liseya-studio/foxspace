import {test,expect} from "@playwright/test";

test("move, resize and preserve free widget positions on a configurable grid",async({page})=>{
 await page.goto("/");
 await page.evaluate(()=>{localStorage.clear();});
 await page.reload();
 await page.locator(".dock-add").click();
 await page.locator(".fox-global-create-items button").filter({hasText:"Экран"}).click();
 await page.getByRole("button",{name:"Действия с экраном"}).click();
 await page.getByRole("button",{name:"Редактировать экран"}).click();
 await page.locator(".fox-grid-config label").filter({hasText:"Столбцы"}).locator("input").fill("16");
 await page.locator(".fox-grid-config label").filter({hasText:"Зазор"}).locator("input").fill("8");
 await page.locator(".fox-editor-library button").filter({hasText:"Текст"}).click();
 const first=page.locator(".fox-widget").first();
 await expect(first).toBeVisible();
 await first.scrollIntoViewIfNeeded();
 const start=await first.locator(".fox-grid-drag-handle").boundingBox();
 if(!start)throw Error("Drag handle is missing");
 const rowStep=64+8;
 await page.mouse.move(start.x+start.width/2,start.y+start.height/2);
 await page.mouse.down();
 await page.mouse.move(start.x+start.width/2,start.y+start.height/2+4*rowStep,{steps:12});
 await page.mouse.up();
 const id=await first.evaluate(el=>{const widgets=JSON.parse(localStorage.getItem("fox-editor-widgets-v1")||"{}");const keys=Object.keys(widgets);return widgets[keys[0]][0].id;});
 const state=await page.evaluate(()=>{const grids=JSON.parse(localStorage.getItem("fox-screen-grid-v1")||"{}");return Object.values(grids)[0] as {settings:{columns:number;gap:number};positions:Record<string,{x:number;y:number;w:number;h:number}>};});
 expect(state.settings.columns).toBe(16);
 expect(state.settings.gap).toBe(8);
 expect(state.positions[id].y).toBeGreaterThanOrEqual(3);
 const before=state.positions[id].h;
 const edge=await first.locator(".fox-widget-edge-bottom").boundingBox();
 if(!edge)throw Error("Resize edge is missing");
 await page.mouse.move(edge.x+edge.width/2,edge.y+edge.height/2);
 await page.mouse.down();
 await page.mouse.move(edge.x+edge.width/2,edge.y+edge.height/2+rowStep*2,{steps:10});
 await page.mouse.up();
 const resized=await page.evaluate((id)=>{const grids=JSON.parse(localStorage.getItem("fox-screen-grid-v1")||"{}");const grid=Object.values(grids)[0] as {positions:Record<string,{h:number}>};return grid.positions[id].h;},id);
 expect(resized).toBeGreaterThan(before);
 await page.reload();
 const saved=await page.evaluate((id)=>{const grids=JSON.parse(localStorage.getItem("fox-screen-grid-v1")||"{}");const grid=Object.values(grids)[0] as {positions:Record<string,{h:number;y:number}>};return grid.positions[id];},id);
 expect(saved.h).toBe(resized);
 expect(saved.y).toBe(state.positions[id].y);
});
